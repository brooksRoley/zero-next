// BARREL — a 5x7 bitmap font for the HUD, drawn as quads by the renderer.
// Rows top to bottom; bit 4 is the leftmost column. Upper case only.
#pragma once
#include <cstdint>

namespace barrel::font {

constexpr int kWidth = 5;
constexpr int kHeight = 7;

// Returns the 7 row masks for c (lower case maps to upper), or nullptr for space.
inline const uint8_t* glyph(char c) {
  static const uint8_t kLetters[26][7] = {
      {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // A
      {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},  // B
      {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E},  // C
      {0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C},  // D
      {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F},  // E
      {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},  // F
      {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F},  // G
      {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // H
      {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E},  // I
      {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C},  // J
      {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11},  // K
      {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},  // L
      {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11},  // M
      {0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11},  // N
      {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // O
      {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},  // P
      {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D},  // Q
      {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},  // R
      {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E},  // S
      {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},  // T
      {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // U
      {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},  // V
      {0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A},  // W
      {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},  // X
      {0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04},  // Y
      {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},  // Z
  };
  static const uint8_t kDigits[10][7] = {
      {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},  // 0
      {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 1
      {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F},  // 2
      {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 3
      {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},  // 4
      {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 5
      {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},  // 6
      {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 7
      {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},  // 8
      {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},  // 9
  };
  static const uint8_t kDot[7] = {0, 0, 0, 0, 0, 0x0C, 0x0C};
  static const uint8_t kColon[7] = {0, 0x0C, 0x0C, 0, 0x0C, 0x0C, 0};
  static const uint8_t kDash[7] = {0, 0, 0, 0x1F, 0, 0, 0};
  static const uint8_t kSlash[7] = {0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10};
  static const uint8_t kPercent[7] = {0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03};
  static const uint8_t kBang[7] = {0x04, 0x04, 0x04, 0x04, 0x04, 0, 0x04};
  static const uint8_t kApos[7] = {0x04, 0x04, 0x08, 0, 0, 0, 0};
  static const uint8_t kPlus[7] = {0, 0x04, 0x04, 0x1F, 0x04, 0x04, 0};
  static const uint8_t kGt[7] = {0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08};
  static const uint8_t kLt[7] = {0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02};
  static const uint8_t kQuestion[7] = {0x0E, 0x11, 0x01, 0x02, 0x04, 0, 0x04};
  static const uint8_t kComma[7] = {0, 0, 0, 0, 0x0C, 0x04, 0x08};
  static const uint8_t kMid[7] = {0, 0, 0, 0x0C, 0x0C, 0, 0};  // ·
  if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');
  if (c >= 'A' && c <= 'Z') return kLetters[c - 'A'];
  if (c >= '0' && c <= '9') return kDigits[c - '0'];
  switch (c) {
    case '.': return kDot;
    case ':': return kColon;
    case '-': return kDash;
    case '/': return kSlash;
    case '%': return kPercent;
    case '!': return kBang;
    case '\'': return kApos;
    case '+': return kPlus;
    case '>': return kGt;
    case '<': return kLt;
    case '?': return kQuestion;
    case ',': return kComma;
    case '*': return kMid;
    default: return nullptr;
  }
}

}  // namespace barrel::font
